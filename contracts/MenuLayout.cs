namespace Sws2Cs2Menus.Contracts;

/// <summary>Presentation hints used by Custom HUD renderers.</summary>
public enum MenuLayout
{
    List,
    Dashboard,
    Confirmation,
    /// <summary>Root options become persistent categories; their submenus fill the right pane.</summary>
    Sidebar,
    /// <summary>Map list with difficulty badges and optional packaged thumbnails.</summary>
    MapPicker
}

/// <summary>Optional action styling supplied through an option's Tag.
/// Glyph is retained for compatibility; the text-only HUD does not render it.</summary>
public sealed record MenuOptionAppearance(string Glyph, bool Destructive = false);

/// <summary>Map presentation supplied through an option's Tag. ThumbnailKey is the stable map ID.</summary>
public sealed record MapMenuOptionAppearance(int? CkzTier, int? VnlTier, string? ThumbnailKey = null)
{
    // Retain the original constructor for consumers with mode-only metadata.
    // Those ambiguous values are not reused for NUB or PRO.
    public MapMenuOptionAppearance(int? ckzNubTier, int? ckzProTier, int? vnlNubTier, int? vnlProTier,
        string? thumbnailKey = null) : this(null, null, thumbnailKey)
    {
        CkzNubTier = ckzNubTier;
        CkzProTier = ckzProTier;
        VnlNubTier = vnlNubTier;
        VnlProTier = vnlProTier;
    }

    public int? CkzNubTier { get; init; }

    public int? CkzProTier { get; init; }

    public int? VnlNubTier { get; init; }

    public int? VnlProTier { get; init; }

    /// <summary>Matches classes generated by tools/build_map_thumbnails.py; no network fetch occurs in-game.</summary>
    public string? ThumbnailClass => string.IsNullOrWhiteSpace(ThumbnailKey) ? null
        : "map-thumb-" + Convert.ToHexStringLower(System.Security.Cryptography.SHA256.HashData(
            System.Text.Encoding.UTF8.GetBytes(ThumbnailKey.ToLowerInvariant())))[..16];
}
